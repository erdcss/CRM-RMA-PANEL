"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const {initialize,execute,backup,restore,invoiceHTML}=require("./backend.cjs");
test("Çalışkan Dükkan - bağımsız offline muhasebe bütünlük testi",async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"dukkan-offline-"));
 await initialize(path.join(dir,"local.sqlite"));
 const p=await execute("addParty",{name:"Örnek Müşteri",kind:"both",tax:"1234567890"});
 const product=await execute("addProduct",{name:"Kahve Makinesi",code:"URUN-01",barcode:"8690000001234",unit:"Adet",purchase:"500",sale:"750"});
 assert.ok(fs.existsSync(path.join(dir,"local.sqlite")),"yerel SQLite dosyası açıldı");
 let list=await execute("list",{kind:"products"});
 assert.equal(list[0].stock_milli,0);
 const firstDate="2026-10-24";
 await execute("addInvoice",{kind:"purchase",number:"ALIS-001",date:firstDate,partyId:p,lines:[{productId:product,qty:"10",price:"500",vat:20}]});
 list=await execute("list",{kind:"products"});
 assert.equal(list[0].stock_milli,10000,"alış stoku artırdı");
 const invoice=await execute("addInvoice",{kind:"sale",number:"SAT-001",date:firstDate,partyId:p,lines:[{productId:product,qty:"3",price:"750",vat:20}]});
 assert.equal(invoice.total_cents,270000,"%20 KDV dahil tutar");
 assert.match(invoiceHTML(invoice.id),/SAT-001/,"dahili yazdırma sayfası");
 list=await execute("list",{kind:"products"});
 assert.equal(list[0].stock_milli,7000,"satış stoku düşürdü");
 const ledger=await execute("list",{kind:"parties"});
 assert.equal(ledger[0].balance,-600000+270000,"cari alış ve satış otomatik işlendi");
 const stockBefore=list[0].stock_milli;
 await assert.rejects(execute("addInvoice",{kind:"sale",number:"SAT-002",date:firstDate,partyId:p,lines:[{productId:product,qty:"9",price:"750",vat:20}]}),/Yetersiz stok|Stok yetersiz/);
 assert.equal((await execute("list",{kind:"products"}))[0].stock_milli,stockBefore,"stok dışına taşan fatura rollback");
 assert.equal((await execute("list",{kind:"invoices"})).length,2);
 await assert.rejects(execute("addInvoice",{kind:"sale",number:"SAT-001",date:firstDate,partyId:p,lines:[{productId:product,qty:"1",price:"750",vat:20}]}),/zaten kayıtlı/);
 await execute("addInvoice",{kind:"sale_return",number:"IADE-001",date:firstDate,partyId:p,lines:[{productId:product,qty:"1",price:"750",vat:20}]});
 assert.equal((await execute("list",{kind:"products"}))[0].stock_milli,8000,"iade stoku geri getirir");
 const bank=await execute("addBank",{name:"Garanti BBVA",iban:"TR000000000000000000000000"});
 await execute("addPayment",{partyId:p,kind:"collection",method:"bank",bankId:bank,amount:"300",date:firstDate});
 const bankRows=await execute("list",{kind:"banks"});assert.equal(bankRows[0].balance,30000,"tahsilat bankayı artırdı");
 const cashBefore=(await execute("dashboard")).cash;
 await execute("addPayment",{partyId:p,kind:"payment",method:"cash",amount:"100",date:firstDate});
 assert.equal((await execute("dashboard")).cash,cashBefore-10000,"nakit ödeme kasayı azaltır");
 const check=await execute("addInstrument",{partyId:p,kind:"cheque",direction:"received",number:"CEK-123",amount:"1250",dueDate:"2026-12-01"});
 await execute("instrumentStatus",{id:check,status:"collected"});
 assert.equal((await execute("list",{kind:"instruments"}))[0].status,"collected");
 assert.equal((await execute("list",{kind:"banks"}))[0].balance,30000,"çek kapama ikinci tahsilat yazmaz");
 const order=await execute("addOrder",{kind:"sale",number:"SIP-001",date:firstDate,partyId:p,lines:[{productId:product,qty:"2",price:"750",vat:20}]});
 await execute("orderStatus",{id:order.id,status:"completed"});
 assert.equal((await execute("list",{kind:"orders"}))[0].status,"completed");
 await execute("adjustStock",{id:product,direction:"decrease",qty:"1.250",notes:"Sayım"});
 assert.equal((await execute("list",{kind:"products"}))[0].stock_milli,6750,"üç basamaklı miktar");
 const snapshot=backup();assert.ok(snapshot.length>1000);
 await execute("addParty",{name:"Geçici Cari",kind:"customer"});
 restore(snapshot);
 assert.equal((await execute("list",{kind:"parties"})).length,1,"yedekten tam geri dönüş");
 assert.equal((await execute("list",{kind:"invoices"})).length,3);
 const report=await execute("report");assert.ok(report.monthly.length>0);
 fs.rmSync(dir,{recursive:true,force:true});
});
